export async function runShopeeSync() {
  console.log(`\n═══════════════════════════════════════════════════════════`);
  console.log(`  🔄 SINCRONIZANDO ANÚNCIOS JÁ ATIVOS NA SHOPEE (${SHOPEE_PRODUCTS.length} itens no PDF)`);
  console.log(`═══════════════════════════════════════════════════════════`);

  // Cria mapa de SKUs normalizados da Shopee
  const shopeeSkuMap = new Map();
  SHOPEE_PRODUCTS.forEach(p => {
    const rawSku = (p.sku || '').toUpperCase().trim();
    if (rawSku) {
      shopeeSkuMap.set(rawSku, p);
      const baseSku = rawSku.replace(/_FULL$/i, '').replace(/_\d+$/i, '');
      if (baseSku !== rawSku) {
        shopeeSkuMap.set(baseSku, p);
      }
    }
  });

  // 1. Sincroniza arquivos JSON em produtos/
  let jsonMatched = 0;
  if (fs.existsSync(PRODUTOS_DIR)) {
    const jsonFiles = fs.readdirSync(PRODUTOS_DIR).filter(f => f.endsWith('.json'));
    for (const file of jsonFiles) {
      const sku = path.basename(file, '.json').toUpperCase().trim();
      const filePath = path.join(PRODUTOS_DIR, file);

      let match = shopeeSkuMap.get(sku);
      if (!match) {
        const base = sku.replace(/_FULL$/i, '').replace(/_\d+$/i, '');
        match = shopeeSkuMap.get(base);
      }
      if (!match) {
        for (const [shopeeSku, p] of shopeeSkuMap.entries()) {
          if (shopeeSku === sku || sku.startsWith(shopeeSku) || shopeeSku.startsWith(sku)) {
            match = p;
            break;
          }
        }
      }

      if (match) {
        try {
          const content = JSON.parse(fs.readFileSync(filePath, 'utf-8'));
          content.is_published = true;
          content.status = "publicado";
          content.shopee_product_id = match.id;
          content.shopee_titulo_ativo = match.nome;
          fs.writeFileSync(filePath, JSON.stringify(content, null, 2), 'utf-8');
          jsonMatched++;
          console.log(`  ✅ [JSON] ${sku} -> APROVADO NA SHOPEE (ID: ${match.id})`);
        } catch (e) {
          console.error(`  ❌ Erro ao atualizar ${file}:`, e.message);
        }
      }
    }
  }

  // 2. Sincroniza a planilha lote_d1fae5.csv
  let csvMatched = 0;
  if (fs.existsSync(CSV_PATH)) {
    const rawCsv = fs.readFileSync(CSV_PATH, 'utf-8');
    const records = parse(rawCsv, { columns: true, skip_empty_lines: true, trim: true, bom: true });

    for (const row of records) {
      const rowSku = (row.sku || '').toUpperCase().trim();
      const parentSku = (row.parent_sku || rowSku.split('_')[0] || '').toUpperCase().trim();

      let match = shopeeSkuMap.get(rowSku) || shopeeSkuMap.get(parentSku);
      if (!match) {
        for (const [shopeeSku, p] of shopeeSkuMap.entries()) {
          if (shopeeSku === rowSku || shopeeSku === parentSku || rowSku.startsWith(shopeeSku) || parentSku.startsWith(shopeeSku)) {
            match = p;
            break;
          }
        }
      }

      if (match) {
        row.status = "publicado";
        row.cor = "#83E28E"; // Verde Concluído
        csvMatched++;
      }
    }

    fs.writeFileSync(CSV_PATH, stringify(records, { header: true }), 'utf-8');
    console.log(`  📊 [CSV] ${csvMatched} linha(s) marcadas como PUBLICADO (#83E28E) no lote.`);
  }

  // 3. Atualiza o diagnóstico do Agente 4
  const { runDiagnostics } = await import('./agent4-diagnostician/diagnose.mjs');
  const updatedDiag = await runDiagnostics();

  console.log(`\n═══════════════════════════════════════════════════════════`);
  console.log(`  🎉 SINCRONIZAÇÃO CONCLUÍDA!`);
  console.log(`  JSONs Aprovados:      ${jsonMatched}`);
  console.log(`  Linhas CSV Aprovadas: ${csvMatched}`);
  console.log(`  Pendentes Restantes:  ${updatedDiag.pendentesResolucao}`);
  console.log(`  Já Resolvidos Ativos: ${updatedDiag.jaResolvidos}`);
  console.log(`═══════════════════════════════════════════════════════════\n`);

  return {
    jsonMatched,
    csvMatched,
    diagnostics: updatedDiag
  };
}

if (process.argv[1] && process.argv[1].endsWith('sync_shopee_catalog.mjs')) {
  runShopeeSync().catch(console.error);
}
